import { type Kind, type Row, type Value } from './model'
import type { Actor } from './store'

// Closed field lists: new domain fields and kinds are private until a purpose declares them.
const common = {
 clients: ['name'], people: ['name','timezone'],
 engagements: ['name','clientId','leadId','members','type','currency','timezone'],
 tasks: ['name','engagementId','remainingSeconds','status'],
 proposals: ['kind','engagementId','status','preparedBy','preparedAt','assumptions','evidence','plan','decidedBy','decidedAt','reason','choice','effect','availability'],
}
const work = {
 time: ['personId','engagementId','taskId','service','start','end','timezone','workDate','durationSeconds','notes','billable','status'],
 expenses: ['personId','engagementId','date','description','reimbursable','status'],
 milestones: ['engagementId','name','date','status'],
}
const scheduling = {
 calendars: ['personId','from','to','dailySeconds','weekdays','holidays','timezone'],
 leave: ['personId','from','to','dailySeconds'],
 staffing: ['engagementId','personId','from','to','dailySeconds','commitment'],
}
export const agentFields: Record<string, Partial<Record<Kind, readonly string[]>>> = {
 time: { ...common, time: work.time, calendars: scheduling.calendars },
 staffing: { ...common, ...scheduling },
 billing: { ...common, ...work },
 'change-order': { ...common, ...work, ...scheduling, budgets: ['engagementId','mode','effortSeconds','roundingSeconds','status'] },
}
const pick = (value: Value, keys: readonly string[]) => Object.fromEntries(keys.filter(k=>Object.hasOwn(value,k)).map(k=>[k,value[k]]))
export function agentValue(a: Actor, k: Kind, value: Value): Value {
 const v = pick(value, agentFields[a.agentScope?.purpose ?? '']?.[k] ?? [])
 if (k === 'proposals') {
  // Plans are generated by the typed preparation command, never copied from imported text.
  const planFields: Record<string,string[]> = { time:['personId','taskId','service','start','end','timezone','notes','billable','ambiguity'],staffing:['alternatives','commitment'],billing:['title','sources'],'change-order':['mode','amountMinor','effortSeconds','roundingSeconds','brief'] }
  v.plan = pick(value.plan, planFields[value.kind] ?? [])
  v.evidence = value.evidence.map((x:Value)=>pick(x,['source','summary','record']))
 }
 return v
}
export function agentData(a: Actor, data: Record<Kind,Row[]>): Record<Kind,Row[]> {
 const purpose=a.agentScope?.purpose ?? '', allowed=new Set(a.agentScope?.engagementIds ?? [])
 const engagements=data.engagements.filter(r=>allowed.has(r.id)),clientIds=new Set(engagements.map(r=>r.value.clientId))
 const people=new Set(engagements.flatMap(r=>[r.value.leadId,...(r.value.members??[])]))
 for(const r of data.staffing)if(allowed.has(r.value.engagementId))people.add(r.value.personId)
 // Resourcing may consider agency people and their availability, but no other engagement's allocations or work.
 if(purpose==='staffing')for(const r of data.people)people.add(r.id)
 return Object.fromEntries(Object.entries(data).map(([kind,rows])=>{
  const k=kind as Kind
  if(!agentFields[purpose]?.[k])return [k,[]]
  const scoped=rows.filter(r=>k==='engagements'?allowed.has(r.id):k==='clients'?clientIds.has(r.id):k==='people'?people.has(r.id):['calendars','leave'].includes(k)?people.has(r.value.personId):allowed.has(r.value.engagementId))
   .filter(r=>k!=='proposals'||(r.value.preparedBy===a.session.operator.id&&r.value.kind===purpose))
   .filter(r=>!['time','expenses','milestones'].includes(k)||r.value.status==='approved')
  return [k,scoped.map(r=>({...r,value:agentValue(a,k,r.value)}))]
 })) as Record<Kind,Row[]>
}
